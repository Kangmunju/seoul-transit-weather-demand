# 팬데믹 구조 변화 분석
# 2019~2024 지하철 수요의 급락과 회복을 확인

from _common import load_merged


def rule(title):
    print("\n" + "=" * 70)
    print(title)
    print("=" * 70)


def main():

    # 전처리된 통합 데이터를 불러옴
    # a4에서는 전처리하기 전 문제가 실제로 있었는지 확인하는 것이 목적 -> SQLite 원본을 직접 읽음
    # a5에서는 팬데믹 전후의 수요 구조를 분석하는 것이 목적 -> 이미 정제된 merged 사용
    # load_merged()가 반환하는 merged에는 clean.py의 전처리와 달력 특징 추가까지 완료되어 있음
    merged, sw, rep = load_merged()

    # a1, a2와 동일하게 정제 완료된 merged를 그대로 사용
    # 날짜순으로 정렬하고 인덱스를 다시 0부터 부여
    d = merged.sort_values("date").reset_index(drop=True).copy()

    # 데이터의 시작 연도와 마지막 연도 확인
    y0 = d["date"].dt.year.min()
    y1 = d["date"].dt.year.max()

    # 단년 데이터라면 팬데믹 구조 변화 분석을 하지 않음
    if y0 == y1:
        print(
            f"[skip] 단년({y0}) 데이터입니다. 팬데믹 분석은 다년에서만 의미가 있습니다."
        )
        return

    # ------------------------------------------------------------
    # 1. 연도별 일평균 이용량
    # ------------------------------------------------------------
    rule("① 연도별 일평균 이용 — 급감과 회복")

    yr = d.groupby(d["date"].dt.year)["ride"].mean()

    # 2019년을 기준으로 비교
    base19 = yr.get(2019, yr.iloc[0])

    print(f"{'연도':<6}{'일평균이용':>16}{'2019대비':>12}")

    for y, v in yr.items():
        print(f"{y:<6}{v:>16,.0f}{(v / base19 - 1) * 100:>+11.1f}%")

    # ------------------------------------------------------------
    # 2. 팬데믹 국면별 평균
    # ------------------------------------------------------------
    rule("② 구조변화 정량화 — 국면별 평균(요일 통제: 평일만)")

    # 요일 효과가 섞이지 않도록 평일만 사용
    wd = d[d["is_workday"] == 1]

    # 팬데믹 이전
    pre = wd.loc[
        wd["date"] < "2020-02-01",
        "ride",
    ].mean()

    # 팬데믹 급성기
    acute = wd.loc[
        (wd["date"] >= "2020-02-01") & (wd["date"] < "2022-04-18"),
        "ride",
    ].mean()

    # 회복기
    recovery = wd.loc[
        (wd["date"] >= "2022-04-18") & (wd["date"] < "2023-05-11"),
        "ride",
    ].mean()

    # 엔데믹 이후
    endemic = wd.loc[
        wd["date"] >= "2023-05-11",
        "ride",
    ].mean()

    periods = [
        ("팬데믹 이전", wd["date"] < "2020-02-01", pre),
        (
            "급성기",
            (wd["date"] >= "2020-02-01") & (wd["date"] < "2022-04-18"),
            acute,
        ),
        (
            "회복기",
            (wd["date"] >= "2022-04-18") & (wd["date"] < "2023-05-11"),
            recovery,
        ),
        ("엔데믹 이후", wd["date"] >= "2023-05-11", endemic),
    ]

    for label, mask, value in periods:
        count = mask.sum()
        change = (value / pre - 1) * 100

        print(
            f"{label:<10} {count:,}일 평일평균 {value:,.0f} (이전대비 {change:+.1f}%)"
        )

    # ------------------------------------------------------------
    # 3. 단순 시계열 모델이 팬데믹에서 무너지는 이유
    # ------------------------------------------------------------
    rule("③ 왜 단순 모델이 무너지나 — a3 walk-forward fold1의 배경")

    # yr : 연도별 일평균 이용량(1에서 미리 만들어두었음)
    # 해당 연도가 없으면 에러를 내는 대신 None을 반환하기 위해 .get() 사용
    mean_2019 = yr.get(2019)
    mean_2020 = yr.get(2020)

    if mean_2019 is not None and mean_2020 is not None:
        change_2020 = (mean_2020 / mean_2019 - 1) * 100

        print(
            f"2019 일평균 {mean_2019:,.0f} → "
            f"2020 일평균 {mean_2020:,.0f} "
            f"({change_2020:+.1f}%)"
        )

        print(
            "'어제/지난주'로 예측하는 모델은 "
            "2020-02~03 급락을 며칠 늦게야 따라잡습니다."
        )

        print(
            "→ a3 walk-forward fold1(train=2019, test=2020)이 "
            "R²<0 로 무너진 이유입니다."
        )

        print(
            "→ 처리: 팬데믹 국면 더미"
            "(pandemic_acute/recovery)를 피처로 넣어 수준 이동을 흡수."
        )

    # ------------------------------------------------------------
    # 4. 팬데믹 전후 요일 구조 변화
    # ------------------------------------------------------------
    rule("④ 요일 구조 변화 — 주말/평일 비율이 바뀌었나")

    # label : 출력할 시기 이름
    # yrs : 실제로 선택할 연도
    for label, yrs in [
        ("2019", [2019]),
        ("2020~21(급성)", [2020, 2021]),
        ("2024", [2024]),
    ]:
        # .isin(yrs)로 해당 연도만 선택
        sub = d[d["date"].dt.year.isin(yrs)]

        wk = sub.loc[
            sub["is_workday"] == 1,
            "ride",
        ].mean()

        we = sub.loc[
            sub["is_weekend"] == 1,
            "ride",
        ].mean()

        print(f"{label:<14} 주말/평일 = {we / wk * 100:.1f}%")


if __name__ == "__main__":
    main()


