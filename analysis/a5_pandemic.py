# 팬데믹 국면별 수요를 비교할 때는 요일 효과가 섞이지 않도록 평일만 사용함
# 국면 경계는 결과를 보고 임의로 정하지 않고 거리두기 해제 등 외부 기준 날짜를 사용함

# a3의 2019 -> 2020 성능 저하는 단순한 모델 문제로만 볼 수 없다고 판단함
# lag / rolling은 과거 패턴을 이용하므로 갑작스러운 수준 이동에 느리게 대응할 가능성 있음
# 시간순 검증의 특정 구간이 무너지면 그 시점의 구조 변화 여부 또한 확인해야 함을 확인

# pandemic_acute / pandemic_recovery로 모델이 팬데믹 국면을 구분하도록 설계함
# 팬데믹은 전체 수요 수준뿐만 아니라 평일, 주말의 상대적 이용 구조 또한 바꿀 수 있음

